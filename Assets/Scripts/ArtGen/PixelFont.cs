        public static int Measure(string text, int spacing = 1) => text.Length == 0 ? 0 : text.Length * (GlyphW + spacing) - spacing;

        /// <summary>Вивести текст (scale — ціле збільшення пікселя).</summary>
        public static void Draw(PixelCanvas canvas, string text, int x, int y, Rgba color, int scale = 1, int spacing = 1)
        {
            int cx = x;
            foreach (char raw in text)
            {
                char ch = char.ToUpperInvariant(raw);
                if (Glyphs.TryGetValue(ch, out string[] rows))
                {
                    for (int r = 0; r < GlyphH; r++)
                    {
                        for (int c = 0; c < GlyphW; c++)
                        {
                            if (rows[r][c] == '#')
                            {
                                canvas.FillRect(cx + c * scale, y + r * scale, scale, scale, color);
                            }
                        }
                    }
                }

                cx += (GlyphW + spacing) * scale;
            }
        }

        public static void DrawCentered(PixelCanvas canvas, string text, int centerX, int y, Rgba color, int scale = 1, int spacing = 1)
        {
            Draw(canvas, text, centerX - Measure(text, spacing) * scale / 2, y, color, scale, spacing);
        }
